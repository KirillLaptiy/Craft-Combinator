local recipeList = ScriptManager.instance:getAllRecipes()
for i = 0, recipeList:size() - 1 do
	local recipe = recipeList:get(i)
	local originalName = recipe:getOriginalname()
	local category = recipe:getCategory()

	if category ~= "Drawing" and Drawing[originalName] then
		recipe:setCategory("Drawing")
	end
	if category ~= "Melee" and Melee[originalName] then
		recipe:setCategory("Melee")
	end
	if category ~= "Tailoring" and Tailoring[originalName] then
		recipe:setCategory("Tailoring")
	end
	if category ~= "Survivalist" and Survivalist[originalName] then
		recipe:setCategory("Survivalist")
	end
    if category ~= nil and Huita[originalName] then
        recipe:setCategory(nil)
    end
	if category ~= "Carpentry" and Carpentry[originalName] then
		recipe:setCategory("Carpentry")
	end
	if category ~= "Firearm" and Firearm[originalName] then
		recipe:setCategory("Firearm")
	end
	if category ~= "Health" and Health[originalName] then
		recipe:setCategory("Health")
	end
	if category ~= "Welding" and Welding[originalName] then
		recipe:setCategory("Welding")
	end
	if category ~= "Mechanics" and Mechanics[originalName] then
		recipe:setCategory("Mechanics")
	end

end